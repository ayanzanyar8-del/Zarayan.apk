    fun calculateJuz(pageNumber: Int): Int {
        val juz = juzList.lastOrNull { it.startPage <= pageNumber }
        return juz?.number ?: 1
    }

    fun getJuzStartPage(juzNumber: Int): Int {
        val juz = juzList.find { it.number == juzNumber }
        return juz?.startPage ?: 1
    }

    fun getSurahForPage(pageNumber: Int): QuranSurah {
        val validPage = pageNumber.coerceIn(1, 604)
        val meta = surahsMeta.lastOrNull { it.pageNumber <= validPage } ?: surahsMeta.first()
        return meta.copy(verses = getVersesForSurahNumber(meta.number))
    }

