    private fun parseTimeToMinutes(timeStr: String): Int {
        val parts = timeStr.trim().split(":")
        if (parts.size >= 2) {
            val h = parts[0].toIntOrNull() ?: 0
            val m = parts[1].toIntOrNull() ?: 0
            return h * 60 + m
        }
        return 0
    }

    fun getDayPrayerTimes(
        year: Int,
        month: Int,
        day: Int,
        fajrOffset: Int = 0,
        dhuhrOffset: Int = 0,
        asrOffset: Int = 0,
        maghribOffset: Int = 0,
        ishaOffset: Int = 0
    ): PrayerTimesCalculator.DayPrayerTimes? {
        val monthList = timetable2026[month] ?: return null
        val dayIndex = day - 1
        if (dayIndex !in monthList.indices) return null

        val line = monthList[dayIndex]
        val times = line.split(",")
        if (times.size == 6) {
            val fajr = (parseTimeToMinutes(times[0]) + fajrOffset).coerceIn(0, 1439)
            val sunrise = parseTimeToMinutes(times[1]).coerceIn(0, 1439)
            val dhuhr = (parseTimeToMinutes(times[2]) + dhuhrOffset).coerceIn(0, 1439)
            val asr = (parseTimeToMinutes(times[3]) + asrOffset).coerceIn(0, 1439)
            val maghrib = (parseTimeToMinutes(times[4]) + maghribOffset).coerceIn(0, 1439)
            val isha = (parseTimeToMinutes(times[5]) + ishaOffset).coerceIn(0, 1439)

            return PrayerTimesCalculator.DayPrayerTimes(
                day = day,
                month = month,
                year = year,
                fajrMinutes = fajr,
                sunriseMinutes = sunrise,
                dhuhrMinutes = dhuhr,
                asrMinutes = asr,
                maghribMinutes = maghrib,
                ishaMinutes = isha
            )
        }
        return null
    }
